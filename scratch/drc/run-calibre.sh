#!/bin/bash
# Run Calibre DRC on the DSH_NMOS/dsh_nmos2 cell.
#
# Two things had to be discovered rather than assumed:
#
# 1. `calibre -drc ... -runset FILE RULE_FILE` is rejected. -runset belongs to
#    `calibre -gui` only. In batch mode the overrides must live in a file that
#    INCLUDES the foundry deck, so the deck itself stays byte-identical (it is
#    reference material, and editing it would make later runs unreproducible).
#    The include happens first, then the runset lines override its placeholders.
#
# 2. GDSII had to come from the strmout BINARY, not from SKILL's streamOut,
#    which returned nil for every calling form and logged nothing at all.
set -e

export PATH=/opt/calibre2015/aoi_cal_2015.2_36.27/pkgs/icv.aoi/bin:/opt/IC617/tools/dfII/bin:$PATH
export MGC_HOME=/opt/calibre2015/aoi_cal_2015.2_36.27
export MGLS_LICENSE_FILE=/opt/calibre2015/license.dat
export CDSHOME=/opt/IC617

WORK=/tmp/drc
DECK=<PDK_ROOT>/calibre/drc/SmicDR10T_<rev>.drc

mkdir -p "$WORK"
cd "$WORK"

# ---- 1. layout -> GDSII -----------------------------------------------------
# -translateUnmappedLPP is required here: SN/SP are drawn on this cell but the
# PDK map file does not carry every implant purpose, and without this flag those
# rectangles are dropped with only a warning. Dropping them would make the DRC
# pass for the wrong reason.
rm -f nmos4.gds
strmout \
  -library DSH_NMOS \
  -strmFile "$WORK/nmos4.gds" \
  -strmVersion 3 \
  -topCell dsh_nmos2 \
  -view layout \
  -techLib smic18ee \
  -layerMap "<PDK_ROOT>/stream/strmoutMap" \
  -translateUnmappedLPP \
  -logFile "$WORK/strmout.log" \
  -summaryFile "$WORK/strmout.summary" > "$WORK/strmout.stdout" 2>&1 || true

if [ ! -s "$WORK/nmos4.gds" ]; then
  echo "GDS WAS NOT PRODUCED"
  tail -20 "$WORK/strmout.stdout"
  exit 1
fi
echo "GDS: $(stat -c %s "$WORK/nmos4.gds") bytes"
grep -E "Rectangles|error\(s\)" "$WORK/strmout.stdout" | head -3

# ---- 2. build the effective rule file --------------------------------------
# include + overrides, in that order, so the later LAYOUT PATH wins.
cat > "$WORK/effective.drc" <<EOF
// Effective DRC rule file: the foundry deck, then the run-specific settings.
// Generated by scratch/drc/run-calibre.sh -- do not edit by hand.
#include "$DECK"

LAYOUT PATH "$WORK/nmos4.gds"
LAYOUT PRIMARY "dsh_nmos4"
LAYOUT SYSTEM GDSII
DRC RESULTS DATABASE "$WORK/nmos4.drc.results" ASCII
DRC SUMMARY REPORT "$WORK/nmos4.drc.summary"
DRC MAXIMUM RESULTS 1000
DRC MAXIMUM VERTEX 4096
EOF

# ---- 3. run -----------------------------------------------------------------
calibre -drc -64 -hier -turbo 2 "$WORK/effective.drc" \
  > "$WORK/calibre.stdout" 2>&1 || true

echo "--- calibre tail ---"
tail -18 "$WORK/calibre.stdout"
echo "--- artefacts ---"
ls -l "$WORK"/nmos4.drc.results "$WORK"/nmos4.drc.summary 2>/dev/null || true

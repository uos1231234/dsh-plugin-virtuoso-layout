"""
What each remaining problem actually needs -- and what a guard ring can and
cannot fix.

This file exists because the user asked the right question: "the layout isn't
connected at all, is it? Or does drawing a ring fix it?" The honest answer is
that a ring fixes ONE of three separate problems, and the other two are bigger.
"""

print("=" * 76)
print("Three separate problems, and what each one needs")
print("=" * 76)
print()

print("PROBLEM 1 -- the D and S nets are the SAME net.")
print()
print("  Measured (connectivity.py):")
print("    NET 1  AA+CT+M1  labels [D, S]    bbox (0.36 -0.04)-(2.04 1.24)")
print()
print("  There is ONE active bar, so the source and the drain are the same piece")
print("  of diffusion. Two contacts on one diffusion are one terminal, not two.")
print("  Calibre still said 4 ports / 4 nets because the labels FORCED names onto")
print("  the geometry -- labelling is not connectivity, it is a claim about it.")
print()
print("  Needs: the active must be CUT into two islands, one under each contact")
print("  column, with the gate between them. That is what makes a transistor.")
print("  A guard ring does nothing for this.")
print()

print("PROBLEM 2 -- the N-well pickup is a floating island.")
print()
print("  Measured: NET 4 = AA+CT+M1 at y 2.84..4.46, label NONE, not touching")
print("  anything else. NET 7 (NW) and NET 8 (SN) are likewise isolated shapes.")
print("  The well exists, satisfies NW_3 and Convention_FLT_NW, and is")
print("  electrically floating.")
print()
print("  Needs: NW has to reach the device, and the pickup metal has to join the")
print("  net that ties the well (VDD). Currently it is a separate island 1.4 um")
print("  above the device with nothing in between.")
print()

print("PROBLEM 3 -- the substrate tie is one small tap on one side.")
print()
print("  NET 2 = AA+CT+M1, label B, bbox (0.40 -1.42)-(2.00 -0.74), i.e. a single")
print("  strip below the device. Real cells distribute the tie AROUND the device")
print("  so the substrate resistance is low everywhere, not just at one edge.")
print()
print("  Needs: a ring. This -- and only this -- is what a guard ring fixes.")
print()

print("=" * 76)
print("So: does drawing a ring fix it?")
print("=" * 76)
print()
print("  ring fixes      PROBLEM 3 (distributed substrate tie)")
print("  ring does NOT   PROBLEM 1 (source and drain merged)")
print("  ring does NOT   PROBLEM 2 (floating well)")
print()
print("  A ring around the current geometry would give one well-tied, well-")
print("  distributed substrate ... around a device that still has no channel.")
print()
print("The order has to be: split the active -> connect the well -> then ring.")
print()

print("=" * 76)
print("Why 393 DRC checks passed on a layout with no transistor")
print("=" * 76)
print()
print("  DRC is a set of LOCAL rules: widths, spaces, enclosures. Every one of")
print("  them is satisfied by two separate shapes that happen to be the right")
print("  distance apart. None of them says 'the source and drain must not be the")
print("  same diffusion' -- that is a DEVICE property, and this deck has zero")
print("  DEVICE statements (measured: grep -c DEVICE = 0).")
print()
print("  LVS is the check that should have caught it, and it did not, because I")
print("  gave it labels that assert the answer: it matched MY netlist against MY")
print("  labels. With D and S on the same diffusion it reported CORRECT, which")
print("  means the netlist itself was wrong -- 'MN1 D G S B' describes a")
print("  transistor that the geometry does not contain.")
print()
print("  Correct test: extract WITHOUT labels, or write the netlist for what is")
print("  actually drawn. A hand-written netlist can only prove label-vs-geometry")
print("  agreement, never that the device is a device.")
